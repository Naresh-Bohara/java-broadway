package controlstm.looping;

public class ForTest {
/*
 * --------------- for loop -----------------
 * # syntax:
 * 		for(initialization; condition; inc/dec){
 * 			statements
 * 		}
 */
	
	
	public static void main(String[] args) {
//		1 times
		System.out.println("Good morning ");
		
//		2 times
		System.out.println("Good morning ");
		
		for(int i=1; i<=500; i++) {
			System.out.println("Good Morning");
		}
	}
	
}
