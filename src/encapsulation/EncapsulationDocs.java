package encapsulation;

public class EncapsulationDocs {
	/*
	 * ---------------- Encapsulation --------------------
	 * # process of data hiding and data binding.
	 * # principle: you can use it but cant modify
	 * # To achieve encapsulation:
	 * 		1. Declare properties of class as private(i.e data hiding)
	 * 		2. Create public getters and setters methods to get and set values to
	 * 			private properties.
	 * 
	 * # syntax:
	 * 		class class_name{
	 * 			
	 * 			// POJO(Plain Old Java Object) or model class
	 * 			// private properties
	 * 			
	 * 			// public getters and setters
	 * 		}
	 */
}
