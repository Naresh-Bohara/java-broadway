package inheritance;

public class InheritanceDocs {
	/*
	 * -------------- Inheritance ------------------
	 * # use for code re-useability.
	 * # process of accessing properties and methods of parent/super/base class to
	 * 	 child/sub/derived class is known as inheritance.
	 * # also known as IS-A relationship.
	 * # its a generalization to specialization process.
	 * # also known as value change of class.
	 * # extends keyword is used in inheritance
	 * # we can't inherit private properties, methods and constructors.
	 * # we can inherit only one class at a time.
	 * # multiple inheritance not exist in java with class.
	 * # we cant inherit final class.
	 * 
	 * # syntax:
	 * 		child_class_name extends parent_class_name{
	 * 			// properties = parent + child
	 * 			// methods = parent + child
	 * 		}
	 */
}
